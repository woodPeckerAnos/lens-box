// 同一段中文开场，随后分别用日语或中文道晚安。尾句按天变化。
export function 双语闲聊(): string[] {
  let 日文 = [
    '今日はもう眠い。',
    '雨、やんだね。',
    '本はまた明日。',
    '布団あったかい。',
    'もうこんな時間。',
    '猫が先に寝た。',
    '電気消すね。',
    '窓だけ閉めてくる。',
  ]
  let 中文 = [
    '我困了。',
    '雨停了。',
    '明天再看书。',
    '被窝真暖。',
    '都这个点了。',
    '猫先睡了。',
    '我关灯啦。',
    '等我关个窗。',
  ]
  return [
    ...日文.map((句) => 句 + '\nおやすみ。\nうん、おやすみ。'),
    ...中文.map((句) => 句 + '\n晚安。\n嗯，晚安。'),
  ].map((末尾) => '到家了吗？\n刚进门，鞋还没脱呢。\n' + 末尾)
}
