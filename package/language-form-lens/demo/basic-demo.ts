import { 形式频率表, 语言形式篇章, 语言形式语料, 语言形式透镜 } from '../src/index.js'

function 输出频率表(名称: string, 表: 形式频率表): void {
  console.log(名称, JSON.stringify({ 分母: 表.分母, 项目: 表.项目.slice(0, 5) }))
}

let 透镜 = new 语言形式透镜({ 词性序列长度: 3, 每项例证上限: 2 })
let 甲 = 透镜.同步剖析文章({
  文本: '  雨停了。风还在吹。小桥湿着。\n我走过去，看了看水，又慢慢走回来。',
  来源标签: '自造短句样本',
})
let 乙 = 透镜.同步剖析文章({
  文本: '雨虽然已经停了，但是河面上仍然浮着一层细细的雾，因此我沿着小桥走过去，又在桥头停留了片刻。\n“水位是3.14米吗？！”他问。我打开API记录，重新确认。',
  来源标签: '自造长句样本',
})
let 快照 = 甲.导出快照()
输出频率表('词频（包括虚词）', 快照.统计.词频)
输出频率表('虚词词项', 快照.统计.虚词词项)
输出频率表('相邻词搭配', 快照.统计.相邻词搭配)
输出频率表('表面词性短序列', 快照.统计.词性短序列)
console.log(
  '句长节奏',
  快照.句长节奏.map((项) => 项.长度),
)
console.log(
  '段长节奏',
  快照.段长节奏.map((项) => 项.长度),
)
for (let 项 of 快照.统计.相邻词搭配.项目.slice(0, 3)) {
  for (let 例证 of 项.例证) {
    console.log('原文例证', 项.项, 例证.起始偏移, 例证.结束偏移, 甲.获得原文().slice(例证.起始偏移, 例证.结束偏移))
  }
}
let 对比 = 甲.对比另一篇章(乙)
console.log(
  '乙的句长节奏',
  乙.导出快照().句长节奏.map((项) => 项.长度),
)
console.log('词性分布差异（乙减甲）', JSON.stringify({ ...对比.词性分布, 项目: 对比.词性分布.项目.slice(0, 5) }))
console.log('句长分布差异（乙减甲）', JSON.stringify(对比.句长分布))
let 语料 = new 语言形式语料([甲, 乙])
console.log('语料样本数', 语料.获得样本数())
输出频率表('按计数聚合的词性分布', 语料.获得统计().词性分布)
console.log('快照恢复后的总词数', 语言形式篇章.从快照恢复(快照).获得统计().词频.分母)
