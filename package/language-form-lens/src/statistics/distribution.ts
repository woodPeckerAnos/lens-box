import { 已解析语言形式配置, 语言形式对比, 语言形式统计 } from '../schema.js'
import { 合并频率表, 对比频率表 } from './frequency-table.js'

export function 校验配置相同(甲: 已解析语言形式配置, 乙: 已解析语言形式配置): void {
  if (甲.词性序列长度 !== 乙.词性序列长度 || 甲.每项例证上限 !== 乙.每项例证上限) {
    throw new Error('比较或聚合要求语言形式配置完全相同')
  }
}

export function 对比统计(甲: 语言形式统计, 乙: 语言形式统计): 语言形式对比 {
  return {
    词频: 对比频率表(甲.词频, 乙.词频),
    词性分布: 对比频率表(甲.词性分布, 乙.词性分布),
    虚词词项: 对比频率表(甲.虚词词项, 乙.虚词词项),
    相邻词搭配: 对比频率表(甲.相邻词搭配, 乙.相邻词搭配),
    词性短序列: 对比频率表(甲.词性短序列, 乙.词性短序列),
    标点分布: 对比频率表(甲.标点分布, 乙.标点分布),
    句长分布: 对比频率表(甲.句长分布, 乙.句长分布),
    段长分布: 对比频率表(甲.段长分布, 乙.段长分布),
  }
}

export function 合并统计(统计们: readonly 语言形式统计[], 例证上限: number): 语言形式统计 {
  return {
    非空白字符数: 统计们.reduce((和, 统计) => 和 + 统计.非空白字符数, 0),
    词频: 合并频率表(
      统计们.map((统计) => 统计.词频),
      例证上限,
    ),
    词性分布: 合并频率表(
      统计们.map((统计) => 统计.词性分布),
      例证上限,
    ),
    虚词词项: 合并频率表(
      统计们.map((统计) => 统计.虚词词项),
      例证上限,
    ),
    相邻词搭配: 合并频率表(
      统计们.map((统计) => 统计.相邻词搭配),
      例证上限,
    ),
    词性短序列: 合并频率表(
      统计们.map((统计) => 统计.词性短序列),
      例证上限,
    ),
    标点分布: 合并频率表(
      统计们.map((统计) => 统计.标点分布),
      例证上限,
    ),
    句长分布: 合并频率表(
      统计们.map((统计) => 统计.句长分布),
      例证上限,
    ),
    段长分布: 合并频率表(
      统计们.map((统计) => 统计.段长分布),
      例证上限,
    ),
  }
}

export function 重定位统计(统计: 语言形式统计, 篇章序号: number): 语言形式统计 {
  let 副本 = structuredClone(统计)
  for (let 表 of [
    副本.词频,
    副本.词性分布,
    副本.虚词词项,
    副本.相邻词搭配,
    副本.词性短序列,
    副本.标点分布,
    副本.句长分布,
    副本.段长分布,
  ]) {
    for (let 项 of 表.项目) {
      for (let 例证 of 项.例证) 例证.篇章序号 = 篇章序号
    }
  }
  return 副本
}
